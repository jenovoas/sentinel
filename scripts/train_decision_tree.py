#!/usr/bin/env python3
"""
train_decision_tree.py — Offline Training and eBPF Export for Decision Tree Classifier (P2)

Generates or trains a max-depth-4 decision tree classifier for `dt_model` in `ai_guardian.c`.
Features:
  0: entropy (S60 raw value, base unit S60_SCALE_0 = 12,960,000)
  1: severity (0=LOW, 1=MEDIUM, 2=HIGH, 3=CRITICAL)
  2: event_type (1=FILE_BLOCKED, 2=EXEC_BLOCKED, 3=FILE_ALLOWED, 4=EXEC_ALLOWED)
  3: pid_hash (PID & 0xFFFF)

Classes:
  0: DT_CLASS_BENIGN
  1: DT_CLASS_SUSPECT
  2: DT_CLASS_MALICIOUS

Usage:
  python3 scripts/train_decision_tree.py [--export-c] [--export-bpftool] [--pin-path PATH]
"""

import argparse
import struct
import sys

S60_SCALE_0 = 12960000

DT_MAX_DEPTH = 4
DT_MAX_NODES = 32
DT_LEAF_INDEX = 0xFFFF

DT_FEAT_ENTROPY = 0
DT_FEAT_SEVERITY = 1
DT_FEAT_EVENT_TYPE = 2
DT_FEAT_PID_HASH = 3

DT_CLASS_BENIGN = 0
DT_CLASS_SUSPECT = 1
DT_CLASS_MALICIOUS = 2


class DtNode:
    def __init__(self, threshold=0, left=DT_LEAF_INDEX, right=DT_LEAF_INDEX, feature=0, cls=0):
        self.threshold = threshold
        self.left = left
        self.right = right
        self.feature = feature
        self.cls = cls

    def pack(self):
        # struct dt_node:
        # __u64 threshold (8 bytes)
        # __u16 left (2 bytes)
        # __u16 right (2 bytes)
        # __u8  feature (1 byte)
        # __u8  class (1 byte)
        # __u8  _reserved[2] (2 bytes)
        # Total: 16 bytes
        return struct.pack("<QHBBBB", self.threshold, self.left, self.right, self.feature, self.cls, 0, 0)


def build_canonical_model():
    """
    Constructs the canonical 32-node decision tree for ME-60OS Ring 0.
    Node 0: If entropy <= 5,000,000 (~0.38 S60) -> Node 1 (Low entropy), else Node 2 (High entropy)
    Node 1: If severity <= 1 (LOW/MEDIUM) -> Node 3 (Benign), else Node 4 (Suspect)
    Node 2: If event_type in (ALLOWED: 3 or 4) -> Node 5 (Allowed high-entropy), else Node 6 (Blocked)
    Node 3: LEAF -> BENIGN
    Node 4: LEAF -> SUSPECT
    Node 5: If severity >= 2 -> Node 7 (Suspect), else Node 8 (Benign)
    Node 6: LEAF -> MALICIOUS
    Node 7: LEAF -> SUSPECT
    Node 8: LEAF -> BENIGN
    """
    nodes = [DtNode() for _ in range(DT_MAX_NODES)]

    # Node 0: Entropy boundary
    nodes[0] = DtNode(threshold=5000000, left=1, right=2, feature=DT_FEAT_ENTROPY, cls=0)

    # Node 1: Severity check on low entropy
    nodes[1] = DtNode(threshold=1, left=3, right=4, feature=DT_FEAT_SEVERITY, cls=0)

    # Node 2: Event type check on high entropy
    nodes[2] = DtNode(threshold=2, left=6, right=5, feature=DT_FEAT_EVENT_TYPE, cls=0)

    # Node 3: Benign leaf
    nodes[3] = DtNode(threshold=0, left=DT_LEAF_INDEX, right=DT_LEAF_INDEX, feature=0, cls=DT_CLASS_BENIGN)

    # Node 4: Suspect leaf
    nodes[4] = DtNode(threshold=0, left=DT_LEAF_INDEX, right=DT_LEAF_INDEX, feature=0, cls=DT_CLASS_SUSPECT)

    # Node 5: Severity check on high-entropy allowed operations
    nodes[5] = DtNode(threshold=1, left=8, right=7, feature=DT_FEAT_SEVERITY, cls=0)

    # Node 6: Malicious leaf (Blocked + High entropy)
    nodes[6] = DtNode(threshold=0, left=DT_LEAF_INDEX, right=DT_LEAF_INDEX, feature=0, cls=DT_CLASS_MALICIOUS)

    # Node 7: Suspect leaf (High entropy + High severity allowed)
    nodes[7] = DtNode(threshold=0, left=DT_LEAF_INDEX, right=DT_LEAF_INDEX, feature=0, cls=DT_CLASS_SUSPECT)

    # Node 8: Benign leaf
    nodes[8] = DtNode(threshold=0, left=DT_LEAF_INDEX, right=DT_LEAF_INDEX, feature=0, cls=DT_CLASS_BENIGN)

    return nodes


def export_c_array(nodes):
    c_lines = [
        "/* Auto-generated by scripts/train_decision_tree.py */",
        "#include \"decision_tree.h\"",
        "",
        "const struct dt_node CANONICAL_DT_MODEL[DT_MAX_NODES] = {",
    ]
    for i, n in enumerate(nodes):
        c_lines.append(
            f"    [{i}] = {{ .threshold = {n.threshold}ULL, .left = {n.left}, .right = {n.right}, "
            f".feature = {n.feature}, .class = {n.cls} }},"
        )
    c_lines.append("};")
    return "\n".join(c_lines)


def export_bpftool_commands(nodes, pin_path="/sys/fs/bpf/sentinel/dt_model"):
    cmds = [f"# Commands to populate {pin_path} in eBPF via bpftool"]
    for i, n in enumerate(nodes):
        raw = n.pack()
        hex_bytes = " ".join(f"{b:02x}" for b in raw)
        key_hex = " ".join(f"{b:02x}" for b in struct.pack("<I", i))
        cmds.append(
            f"bpftool map update pinned {pin_path} key hex {key_hex} value hex {hex_bytes} # node {i} (feat={n.feature}, thr={n.threshold}, l={n.left}, r={n.right}, cls={n.cls})"
        )
    return "\n".join(cmds)


def main():
    parser = argparse.ArgumentParser(description="Train and export ME-60OS decision tree")
    parser.add_argument("--export-c", action="store_true", help="Print C static array")
    parser.add_argument("--export-bpftool", action="store_true", help="Print bpftool map update commands")
    parser.add_argument("--pin-path", default="/sys/fs/bpf/sentinel/dt_model", help="Path to pinned map")
    args = parser.parse_args()

    nodes = build_canonical_model()

    if args.export_c:
        print(export_c_array(nodes))
    elif args.export_bpftool:
        print(export_bpftool_commands(nodes, args.pin_path))
    else:
        print("Decision Tree Canonical Model Summary:")
        for i in range(9):
            n = nodes[i]
            print(f"  Node {i:02d}: feat={n.feature} threshold={n.threshold} left={n.left} right={n.right} class={n.cls}")
        print(f"\nTotal nodes defined: {len(nodes)} (packed size: {len(nodes) * 16} bytes)")
        print("\nUse --export-c or --export-bpftool to generate integration code.")


if __name__ == "__main__":
    main()
